#!/usr/bin/env node
// Gate: the site can never quietly out-claim the repo.
//
//   node tools/site/check-matrix.mjs           check, exit 1 on any drift
//   node tools/site/check-matrix.mjs --write    regenerate the JSON from README
//
// It parses README.md's capability table and checks three things agree:
//   1. site/data/matrix.json          — every row, cell, tag, note, footnote
//   2. site/data/evidence.json        — the tag vocabulary and the cell counts
//   3. site/status.html               — the rendered table, cell for cell
// and one thing does not exist: a cell tagged `dev`.
//
// Zero dependencies. This file is also the only parser — the JSON in site/data
// is generated by running it with --write, never hand-edited.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const WRITE = process.argv.includes('--write');

const problems = [];
const fail = (m) => problems.push(m);

/* ── README parsing ────────────────────────────────────────────────────── */

const SUP = { '¹': 1, '²': 2, '³': 3, '⁴': 4, '⁵': 5, '⁶': 6, '⁷': 7, '⁸': 8, '⁹': 9, '⁰': 0 };
const SUP_CHARS = Object.keys(SUP).join('');
const SUP_RE = new RegExp(`[${SUP_CHARS}]+`, 'g');

// A run of superscripts is one footnote number: ¹³ is 13, not 1 and 3.
function footnotesOf(text) {
  return (text.match(SUP_RE) || []).map((run) => Number([...run].map((c) => SUP[c]).join('')));
}

// Longest tag first: `E2E*` has to win over `E2E`. `dev` was absent from this
// list while it was unreachable; it is reachable now.
const TAGS = ['E2E*', 'E2E', 'unit', 'smoke', 'bld', 'code', 'dev', 'wall', '—'];

function parseCell(raw) {
  const bold = /^\*\*.*\*\*/.test(raw.replace(SUP_RE, ''));
  const plain = raw.replace(/\*\*/g, '').replace(SUP_RE, '').trim();
  const fn = footnotesOf(raw);
  const tag = TAGS.find((t) => plain === t || plain.startsWith(t + ' ')) ?? null;
  const note = tag ? plain.slice(tag.length).trim() : plain;
  return {
    raw: raw.trim(),
    tag,
    ...(note ? { note } : {}),
    ...(fn.length ? { fn } : {}),
    ...(bold ? { bold } : {}),
  };
}

const splitRow = (l) =>
  l.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((c) => c.trim());

function parseReadme() {
  const readme = readFileSync(path.join(ROOT, 'README.md'), 'utf8');
  const lines = readme.split('\n');

  const head = lines.findIndex((l) => l.startsWith('| Capability |'));
  if (head < 0) throw new Error('README.md: capability table not found');

  const platforms = splitRow(lines[head])
    .slice(1)
    .map((h) => {
      const fn = footnotesOf(h);
      return { name: h.replace(SUP_RE, '').trim(), ...(fn.length ? { fn } : {}) };
    });

  const rows = [];
  for (let i = head + 2; i < lines.length && lines[i].startsWith('|'); i++) {
    const cells = splitRow(lines[i]);
    rows.push({
      capability: cells[0].replace(/\*\*/g, ''),
      capabilityRaw: cells[0],
      cells: cells.slice(1).map(parseCell),
    });
  }

  // Footnote bodies follow the table, one per superscript-led paragraph.
  const footnotes = {};
  let current = null;
  for (let i = head + 2 + rows.length; i < lines.length; i++) {
    const l = lines[i];
    if (l.startsWith('## ')) break;
    const m = l.match(new RegExp(`^([${SUP_CHARS}]+) (.*)$`));
    if (m) {
      current = Number([...m[1]].map((c) => SUP[c]).join(''));
      footnotes[current] = m[2];
    } else if (current && l.trim()) footnotes[current] += ' ' + l.trim();
    else if (!l.trim()) current = null;
  }

  // The tag legend, from the README's own "How to read a cell" table.
  const legendHead = lines.findIndex((l) => l.startsWith('| Tag | Meaning |'));
  if (legendHead < 0) throw new Error('README.md: tag legend table not found');
  const definitions = {};
  for (let i = legendHead + 2; i < lines.length && lines[i].startsWith('|'); i++) {
    const [tag, meaning] = splitRow(lines[i]);
    definitions[tag.replace(/`/g, '')] = meaning.replace(/\*\*/g, '');
  }

  // The three headline figures, from the README's own re-verification line.
  // Collapse whitespace first — that sentence wraps across source lines.
  const flat = readme.replace(/\s+/g, ' ');
  const figures = {};
  for (const [key, re] of [
    ['swift', /(\d+)\/\d+ Swift tests/],
    ['go', /(\d+)\/\d+ Go vectors/],
    ['kotlin', /(\d+)\/\d+ Kotlin vectors/],
  ]) {
    const m = flat.match(re);
    if (!m) throw new Error(`README.md: could not find the ${key} figure`);
    figures[key] = Number(m[1]);
  }

  const counts = {};
  let claimed = 0;
  for (const r of rows) {
    for (const c of r.cells) {
      const key = c.tag ?? 'none';
      counts[key] = (counts[key] || 0) + 1;
      // Cells that could one day turn `dev`. `wall` never can — the platform
      // forbids it — and `—` has nothing to verify.
      if (c.tag && c.tag !== '—' && c.tag !== 'wall') claimed++;
    }
  }

  return {
    figures,
    matrix: {
      $comment:
        'GENERATED — do not hand-edit. Run: node tools/site/check-matrix.mjs --write. CI fails if this drifts from the README table or from site/status.html.',
      source: 'README.md — Capability × platform matrix',
      platforms,
      rows,
      footnotes,
      totals: {
        rows: rows.length,
        platforms: platforms.length,
        cells: rows.length * platforms.length,
        claimed,
        verified: counts.dev ?? 0,
      },
    },
    evidence: {
      $comment: 'GENERATED — do not hand-edit. Tag vocabulary and cell counts, both from README.md.',
      order: ['E2E', 'E2E*', 'unit', 'smoke', 'bld', 'code', 'wall', '—', 'dev'],
      definitions,
      counts,
      deviceVerified: counts.dev || 0,
    },
  };
}

/* ── run ───────────────────────────────────────────────────────────────── */

const fresh = parseReadme();
const MATRIX = path.join(ROOT, 'site/data/matrix.json');
const EVIDENCE = path.join(ROOT, 'site/data/evidence.json');

if (WRITE) {
  writeFileSync(MATRIX, JSON.stringify(fresh.matrix, null, 2) + '\n');
  writeFileSync(EVIDENCE, JSON.stringify(fresh.evidence, null, 2) + '\n');
  const t = fresh.matrix.totals;
  console.log(`wrote matrix.json + evidence.json — ${t.rows} × ${t.platforms} = ${t.cells} cells, ${t.claimed} claimed`);
  process.exit(0);
}

const onDisk = {
  matrix: JSON.parse(readFileSync(MATRIX, 'utf8')),
  evidence: JSON.parse(readFileSync(EVIDENCE, 'utf8')),
};

// 1 + 2. The JSON must be exactly what the README produces.
for (const which of ['matrix', 'evidence']) {
  const a = JSON.stringify(fresh[which], null, 2);
  const b = JSON.stringify(onDisk[which], null, 2);
  if (a !== b) {
    const al = a.split('\n');
    const bl = b.split('\n');
    const i = al.findIndex((l, n) => l !== bl[n]);
    fail(
      `site/data/${which}.json has drifted from README.md (first difference at line ${i + 1}):\n` +
        `      README says: ${al[i]?.trim()}\n` +
        `      file says:   ${bl[i]?.trim()}\n` +
        `      fix with: node tools/site/check-matrix.mjs --write`,
    );
  }
}

// 3. The rendered table must be exactly what the JSON describes.
const html = readFileSync(path.join(ROOT, 'site/status.html'), 'utf8');
const tableMatch = html.match(/<table class="matrix"[\s\S]*?<\/table>/);
if (!tableMatch) fail('site/status.html: no <table class="matrix"> found');
else {
  const table = tableMatch[0];
  const bodyRows = [...table.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)]
    .map((m) => m[1])
    .filter((r) => r.includes('<td'));
  const want = fresh.matrix.rows;

  if (bodyRows.length !== want.length) {
    fail(`site/status.html: table has ${bodyRows.length} rows, matrix.json has ${want.length}`);
  } else {
    want.forEach((row, ri) => {
      const cells = [...bodyRows[ri].matchAll(/<td[^>]*data-tag="([^"]*)"[^>]*data-fn="([^"]*)"/g)];
      if (cells.length !== row.cells.length) {
        fail(`site/status.html row ${ri + 1} (${row.capability}): ${cells.length} cells, want ${row.cells.length}`);
        return;
      }
      row.cells.forEach((cell, ci) => {
        const gotTag = cells[ci][1];
        const gotFn = cells[ci][2];
        const wantTag = cell.tag ?? '';
        const wantFn = (cell.fn ?? []).join(',');
        const where = `${row.capability} / ${fresh.matrix.platforms[ci].name}`;
        if (gotTag !== wantTag) fail(`site/status.html: ${where} renders tag "${gotTag}", matrix.json says "${wantTag}"`);
        if (gotFn !== wantFn) fail(`site/status.html: ${where} renders footnotes "${gotFn}", matrix.json says "${wantFn}"`);
      });
    });
  }

  // Every footnote the table references must be defined on the page.
  const referenced = new Set([...table.matchAll(/href="#fn-(\d+)"/g)].map((m) => m[1]));
  for (const id of referenced) {
    if (!html.includes(`id="fn-${id}"`)) fail(`site/status.html: footnote ${id} is linked but never defined`);
  }
  const defined = new Set([...html.matchAll(/id="fn-(\d+)"/g)].map((m) => m[1]));
  for (const id of Object.keys(fresh.matrix.footnotes)) {
    if (!defined.has(id)) fail(`site/status.html: README footnote ${id} is missing from the page`);
  }
}

// 4. `dev` is the tag that matters most, so it is counted, not trusted.
const DEV = fresh.evidence.counts.dev ?? 0;
const macTag = (cap) => {
  const hits = fresh.matrix.rows.filter(
    (r) => r.capability === cap || r.capability.startsWith(cap + ' ('),
  );
  return hits.length === 1 ? (hits[0].cells[0].tag ?? '') : null;
};

for (const page of ['index', 'status', 'story', 'protocol', 'roadmap', 'build']) {
  const src = readFileSync(path.join(ROOT, `site/${page}.html`), 'utf8');

  // The matrix renders exactly as many dev cells as the README earns.
  const cells = src.match(/<td[\s\S]*?<\/td>/g) ?? [];
  const inCells = cells.filter((c) => /\btag--dev\b/.test(c)).length;
  if (page === 'status' && inCells !== DEV) {
    fail(`site/status.html renders ${inCells} dev cell(s); README has ${DEV}`);
  }
  if (page !== 'status' && inCells) {
    fail(`site/${page}.html renders a dev tag in a table cell; only the matrix may`);
  }

  // The home page's capability cards carry the macOS tag for that capability.
  // Checking every card, not just the dev ones, is what makes a dev pill there
  // trustworthy at all.
  for (const card of src.match(/<li class="cap">[\s\S]*?<\/li>/g) ?? []) {
    const name = card.match(/<h3>([^<]*)<\/h3>/)?.[1]?.trim();
    const tag = card.match(/<abbr class="tag tag--[\w-]+"[^>]*>([^<]*)<\/abbr>/)?.[1]?.trim();
    if (!name || !tag) {
      fail(`site/${page}.html: a capability card is missing its name or tag`);
      continue;
    }
    const want = macTag(name);
    if (want === null) fail(`site/${page}.html: capability card "${name}" matches no single matrix row`);
    else if (want !== tag) fail(`site/${page}.html: card "${name}" shows ${tag}; macOS cell is ${want}`);
  }

  // Anywhere else, a dev pill would be an unbacked claim.
  const stripped = src
    .replace(/<dl class="legend[\s\S]*?<\/dl>/g, '')
    .replace(/<td[\s\S]*?<\/td>/g, '')
    .replace(/<li class="cap">[\s\S]*?<\/li>/g, '');
  if (/\btag--dev\b/.test(stripped)) {
    fail(`site/${page}.html renders a dev tag outside a matrix cell, a card and a legend`);
  }

  const shown = src.match(/<dd id="def-dev"[^>]*>[\s\S]*?>(\d+) cells?</)?.[1];
  if (shown !== undefined && Number(shown) !== DEV) {
    fail(`site/${page}.html: the dev legend reads ${shown} cells; README has ${DEV}`);
  }
}

// 5. Any total the prose states must be the total the data holds. Marked up as
// <span data-total="cells">90</span> so a stale number cannot survive a README
// edit just because it reads fluently.
for (const page of ['index', 'status', 'story', 'protocol', 'roadmap', 'build']) {
  const src = readFileSync(path.join(ROOT, `site/${page}.html`), 'utf8');
  for (const m of src.matchAll(/<span data-total="(\w+)">([^<]*)<\/span>/g)) {
    const [, key, shown] = m;
    const want = fresh.matrix.totals[key];
    if (want === undefined) fail(`site/${page}.html: data-total="${key}" is not a known total`);
    else if (shown !== String(want)) fail(`site/${page}.html says ${key} is ${shown}; matrix.json says ${want}`);
  }
  for (const m of src.matchAll(/data-fig="(\w+)">([^<]*)</g)) {
    const [, key, shown] = m;
    const want = fresh.figures[key];
    if (want === undefined) fail(`site/${page}.html: data-fig="${key}" is not a known figure`);
    else if (shown !== String(want)) fail(`site/${page}.html says ${key} is ${shown}; README says ${want}`);
  }
}

// The seal is the load-bearing fact of the whole protocol claim, so it has to
// be on every page, not just the one that talks about it.
for (const page of ['index', 'status', 'story', 'protocol', 'roadmap', 'build']) {
  const src = readFileSync(path.join(ROOT, `site/${page}.html`), 'utf8');
  if (!/<p class="seal"/.test(src)) fail(`site/${page}.html has no three-impl seal in its footer`);
}

/* ── report ────────────────────────────────────────────────────────────── */

const t = fresh.matrix.totals;
const c = fresh.evidence.counts;
console.log(`README: ${t.rows} capabilities × ${t.platforms} platforms = ${t.cells} cells`);
console.log(
  '  ' +
    fresh.evidence.order
      .map((tag) => `${tag} ${c[tag] ?? 0}`)
      .concat(c.none ? [`untagged ${c.none}`] : [])
      .join(' · '),
);
console.log(`  ${t.claimed} cells name an implementation and could carry dev; ${c.dev ?? 0} do.`);
const f = fresh.figures;
console.log(`  seal: Swift ${f.swift} tests · Go ${f.go} vectors · Kotlin ${f.kotlin} vectors`);

if (problems.length) {
  console.error('\nmatrix gate FAILED:');
  for (const p of problems) console.error('  · ' + p);
  process.exit(1);
}
console.log('\nmatrix gate passed — README, matrix.json, evidence.json and status.html all agree.');
